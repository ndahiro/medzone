// Dates are relative to the day the seed runs, so a freshly seeded database
// always has a live schedule (tomorrow, later this week) instead of visits
// that were "scheduled" months ago.
const SEED_DAY = new Date();
const pad2 = (n) => String(n).padStart(2, '0');

/** Local calendar date, offset from today. */
const isoDate = (offsetDays) => {
  const d = new Date(SEED_DAY.getFullYear(), SEED_DAY.getMonth(), SEED_DAY.getDate() + offsetDays, 12);
  return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}`;
};

/** Local instant with the machine's UTC offset, e.g. 2026-10-20T10:30:00-07:00. */
const isoInstant = (offsetDays, hour, minute = 0) => {
  const d = new Date(
    SEED_DAY.getFullYear(),
    SEED_DAY.getMonth(),
    SEED_DAY.getDate() + offsetDays,
    hour,
    minute,
    0,
    0,
  );
  const offset = -d.getTimezoneOffset();
  const sign = offset >= 0 ? '+' : '-';
  const offH = pad2(Math.floor(Math.abs(offset) / 60));
  const offM = pad2(Math.abs(offset) % 60);
  return `${d.getFullYear()}-${pad2(d.getMonth() + 1)}-${pad2(d.getDate())}T${pad2(d.getHours())}:${pad2(d.getMinutes())}:00${sign}${offH}:${offM}`;
};

/** Display time for a 24-hour clock value, e.g. 14:30 -> "2:30 PM". */
const displayTime = (hour, minute = 0) => {
  const suffix = hour >= 12 ? 'PM' : 'AM';
  const h = hour % 12 || 12;
  return `${h}:${pad2(minute)} ${suffix}`;
};

/** A visit's display date/time and its canonical scheduled instant. */
const at = (offsetDays, hour, minute = 0) => ({
  date: isoDate(offsetDays),
  time: displayTime(hour, minute),
  scheduledStart: isoInstant(offsetDays, hour, minute),
});

/** "2026-10-12" -> "October 12, 2026" (for the follow-up display field). */
const friendlyDate = (offsetDays) => {
  const d = new Date(SEED_DAY.getFullYear(), SEED_DAY.getMonth(), SEED_DAY.getDate() + offsetDays, 12);
  return d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric' });
};

